//! SVG serializer. Walks the canvas element tree and emits markup byte-for-byte
//! compatible with `DiceBear`'s `Renderer` for default options.

use std::collections::HashSet;
use std::fmt::Write as _;

use crate::definition::{AttrMap, ComponentDef, ElementDef, MetaDef, STYLE};
use crate::number::{equals, format as nf};
use crate::prng::fnv1a_hex;
use crate::resolver::Resolver;
use crate::xml::escape;

pub struct Renderer<'a> {
    resolver: &'a Resolver,
    defs: Vec<(String, String)>,
    def_keys: HashSet<String>,
    hash: String,
}

impl<'a> Renderer<'a> {
    pub fn new(resolver: &'a Resolver, seed: &str) -> Self {
        let source_name = STYLE.meta.source.name.as_deref().unwrap_or("");
        let hash = fnv1a_hex(&format!("{source_name}:{seed}"));
        Self {
            resolver,
            defs: Vec::new(),
            def_keys: HashSet::new(),
            hash,
        }
    }

    pub fn render(&mut self) -> String {
        let canvas = &STYLE.canvas;
        let width = canvas.width;
        let height = canvas.height;

        let background = self.render_background(width, height);
        let mut body = self.render_elements(&canvas.elements);
        // Global scale/flip/rotate/translate are all identity for default
        // options, so they are no-ops. Border radius (0) always clips.
        body = self.apply_border_radius(&format!("{background}{body}"), width, height);

        let metadata = license_xml();
        let inner: String = self.defs.iter().map(|(_, v)| v.as_str()).collect();
        let defs = if inner.is_empty() {
            String::new()
        } else {
            format!("<defs>{inner}</defs>")
        };

        let mut attrs = vec![
            "xmlns=\"http://www.w3.org/2000/svg\"".to_owned(),
            format!("viewBox=\"0 0 {} {}\"", nf(width), nf(height)),
        ];
        let root = self.render_attributes(&STYLE.attributes);
        if !root.is_empty() {
            attrs.push(root.trim_start().to_owned());
        }
        attrs.push("aria-hidden=\"true\"".to_owned());
        let attrs_str = attrs.join(" ");

        format!(
            "<svg {attrs_str}><!-- Generated by DiceBear (https://www.dicebear.com) \
             -->{metadata}{defs}{body}</svg>"
        )
    }

    fn render_background(&self, width: f64, height: f64) -> String {
        if self.resolver.color("background").is_empty() {
            return String::new();
        }
        let fill = self.resolve_color_reference("background");
        format!(
            "<rect width=\"{}\" height=\"{}\" fill=\"{}\"/>",
            nf(width),
            nf(height),
            escape(&fill)
        )
    }

    /// Always clips to the canvas rectangle (rounded by `borderRadius`, which
    /// defaults to 0) and registers the `clipPath` in `<defs>`.
    fn apply_border_radius(&mut self, body: &str, width: f64, height: f64) -> String {
        let radius = 0.0;
        let id = format!("clip-{}", self.hash);
        let rx = nf(radius / 100.0 * width);
        let ry = nf(radius / 100.0 * height);
        let def = format!(
            "<clipPath id=\"{id}\"><rect width=\"{}\" height=\"{}\" rx=\"{rx}\" \
             ry=\"{ry}\"/></clipPath>",
            nf(width),
            nf(height)
        );
        self.defs.push((id.clone(), def));
        format!("<g clip-path=\"url(#{id})\">{body}</g>")
    }

    fn render_elements(&mut self, elements: &[ElementDef]) -> String {
        let mut out = String::new();
        for el in elements {
            out.push_str(&self.render_element(el));
        }
        out
    }

    fn render_element(&mut self, element: &ElementDef) -> String {
        match element {
            ElementDef::Element {
                name,
                attributes,
                children,
            } => self.render_svg_element(name, attributes, children),
            ElementDef::Text { value } => {
                let resolved = resolve_value(value);
                if resolved.is_empty() {
                    String::new()
                } else {
                    escape(&resolved)
                }
            }
            ElementDef::Component { .. } => self.render_component_element(element),
        }
    }

    fn render_svg_element(
        &mut self,
        name: &str,
        attributes: &AttrMap,
        children: &[ElementDef],
    ) -> String {
        if name == "defs" {
            for child in children {
                let rendered = self.render_element(child);
                if !rendered.is_empty() {
                    let id = child
                        .attributes()
                        .and_then(|a| a.get("id"))
                        .and_then(|v| v.as_str())
                        .map_or_else(|| format!("_{}", self.defs.len()), str::to_owned);
                    self.insert_def(id, rendered);
                }
            }
            return String::new();
        }

        let attrs = self.render_attributes(attributes);
        let rendered_children = self.render_elements(children);
        if rendered_children.is_empty() {
            format!("<{name}{attrs}/>")
        } else {
            format!("<{name}{attrs}>{rendered_children}</{name}>")
        }
    }

    fn render_component_element(&mut self, element: &ElementDef) -> String {
        let ElementDef::Component { name, attributes } = element else {
            return String::new();
        };
        let Some(variant_name) = self.resolver.variant(name) else {
            return String::new();
        };
        let Some(component) = STYLE.components.get(name) else {
            return String::new();
        };
        let resolved = component.resolve(&STYLE.components);
        let Some(variant) = resolved.variants.get(&variant_name) else {
            return String::new();
        };

        let source_name = component.extends.clone().unwrap_or_else(|| name.clone());
        let id = format!("{source_name}-{variant_name}-{}", self.hash);
        if !self.def_keys.contains(&id) {
            let body = self.render_elements(&variant.elements);
            self.insert_def(id.clone(), format!("<g id=\"{id}\">{body}</g>"));
        }

        let transforms = self.build_transforms(name, resolved);
        let mut merged = attributes.clone();
        if !transforms.is_empty() {
            let user_transform = merged
                .get("transform")
                .and_then(|v| v.as_str())
                .filter(|s| !s.is_empty())
                .map(str::to_owned);
            let parts: Vec<String> = match user_transform {
                Some(first) => {
                    let mut combined = Vec::with_capacity(transforms.len() + 1);
                    combined.push(first);
                    combined.extend(transforms);
                    combined
                }
                None => transforms,
            };
            merged.insert(
                "transform".to_owned(),
                serde_json::Value::String(parts.join(" ")),
            );
        }
        let attrs = self.render_attributes(&merged);
        format!("<use{attrs} href=\"#{id}\"/>")
    }

    fn build_transforms(&self, name: &str, resolved: &ComponentDef) -> Vec<String> {
        let t = self.resolver.component_transform(name);
        if equals(t.rotate, 0.0)
            && equals(t.translate_x, 0.0)
            && equals(t.translate_y, 0.0)
            && equals(t.scale, 1.0)
        {
            return Vec::new();
        }
        let width = resolved.width.unwrap_or(0.0);
        let height = resolved.height.unwrap_or(0.0);
        let cx = width / 2.0;
        let cy = height / 2.0;
        let mut transforms = Vec::new();
        if !equals(t.translate_x, 0.0) || !equals(t.translate_y, 0.0) {
            transforms.push(format!(
                "translate({}, {})",
                nf(t.translate_x / 100.0 * width),
                nf(t.translate_y / 100.0 * height)
            ));
        }
        if !equals(t.rotate, 0.0) {
            transforms.push(format!("rotate({}, {}, {})", nf(t.rotate), nf(cx), nf(cy)));
        }
        if !equals(t.scale, 1.0) {
            transforms.push(format!(
                "translate({}, {}) scale({}) translate({}, {})",
                nf(cx),
                nf(cy),
                nf(t.scale),
                nf(-cx),
                nf(-cy)
            ));
        }
        transforms
    }

    fn render_attributes(&self, attributes: &AttrMap) -> String {
        let mut parts = Vec::new();
        for (key, value) in attributes {
            if value.is_null() {
                continue;
            }
            let resolved = resolve_attribute_value(value, self);
            parts.push(format!("{key}=\"{}\"", escape(&resolved)));
        }
        if parts.is_empty() {
            String::new()
        } else {
            format!(" {}", parts.join(" "))
        }
    }

    fn resolve_color_reference(&self, name: &str) -> String {
        let colors = self.resolver.color(name);
        // Default colorFill is `solid`; constellation never uses gradients.
        colors.first().cloned().unwrap_or_else(|| "none".to_owned())
    }

    fn insert_def(&mut self, id: String, markup: String) {
        if self.def_keys.insert(id.clone()) {
            self.defs.push((id, markup));
        }
    }
}

/// Resolves an attribute value: literal strings pass through, color references
/// are dereferenced through the resolver.
fn resolve_attribute_value(value: &serde_json::Value, renderer: &Renderer) -> String {
    if let Some(s) = value.as_str() {
        return s.to_owned();
    }
    if let Some(obj) = value.as_object() {
        let kind = obj.get("type").and_then(|v| v.as_str()).unwrap_or("");
        let name = obj.get("name").and_then(|v| v.as_str()).unwrap_or("");
        return match kind {
            "color" => renderer.resolve_color_reference(name),
            _ => String::new(),
        };
    }
    String::new()
}

/// Resolves a text element value: literal strings pass through.
fn resolve_value(value: &serde_json::Value) -> String {
    value.as_str().unwrap_or("").to_owned()
}

// Left/right double quotation marks. Byte parity requires the exact code
// points DiceBear emits, so they are kept verbatim rather than ASCII-ized.
const LDQ: char = '\u{201C}';
const RDQ: char = '\u{201D}';

/// Builds the `<metadata>` Dublin Core block (`License.xml`).
fn license_xml() -> String {
    let meta = &STYLE.meta;
    let title = meta.source.name.as_deref().unwrap_or("");
    let creator = meta.creator.name.as_deref().unwrap_or("");
    let source_url = meta.source.url.as_deref().unwrap_or("");
    let license_url = meta.license.url.as_deref().unwrap_or("");
    let rights = license_text(meta);

    if title.is_empty()
        && creator.is_empty()
        && source_url.is_empty()
        && license_url.is_empty()
        && rights.is_empty()
    {
        return String::new();
    }

    let mut fields = String::new();
    if !title.is_empty() {
        let _ = write!(fields, "<dc:title>{}</dc:title>", escape(title));
    }
    if !creator.is_empty() {
        let _ = write!(fields, "<dc:creator>{}</dc:creator>", escape(creator));
    }
    if !source_url.is_empty() {
        let _ = write!(
            fields,
            "<dc:source xsi:type=\"dcterms:URI\">{}</dc:source>",
            escape(source_url)
        );
    }
    if !license_url.is_empty() {
        let _ = write!(
            fields,
            "<dcterms:license xsi:type=\"dcterms:URI\">{}</dcterms:license>",
            escape(license_url)
        );
    }
    if !rights.is_empty() {
        let _ = write!(fields, "<dc:rights>{}</dc:rights>", escape(&rights));
    }

    format!(
        "<metadata xmlns:rdf=\"http://www.w3.org/1999/02/22-rdf-syntax-ns#\" \
         xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" \
         xmlns:dc=\"http://purl.org/dc/elements/1.1/\" \
         xmlns:dcterms=\"http://purl.org/dc/terms/\">\
         <rdf:RDF><rdf:Description>{fields}</rdf:Description></rdf:RDF></metadata>"
    )
}

/// Builds the human-readable attribution string (`License.text`).
fn license_text(meta: &MetaDef) -> String {
    let source_name = meta.source.name.as_deref().unwrap_or("");
    let source_url = meta.source.url.as_deref().unwrap_or("");
    let creator_name = meta.creator.name.as_deref().unwrap_or("");
    let license_name = meta.license.name.as_deref().unwrap_or("");
    let license_url = meta.license.url.as_deref().unwrap_or("");

    if source_name.is_empty() && creator_name.is_empty() && license_name.is_empty() {
        return String::new();
    }

    let mut title = if source_name.is_empty() {
        "Design".to_owned()
    } else {
        format!("{LDQ}{source_name}{RDQ}")
    };
    if !source_url.is_empty() {
        let _ = write!(title, " ({source_url})");
    }

    let creator_label = if creator_name.is_empty() {
        format!("{LDQ}Unknown{RDQ}")
    } else {
        format!("{LDQ}{creator_name}{RDQ}")
    };

    let mut result = String::new();
    // "Remix of" is skipped for MIT or DiceBear-original styles.
    if license_name != "MIT" && creator_name != "DiceBear" && !source_name.is_empty() {
        result.push_str("Remix of ");
    }
    let _ = write!(result, "{title} by {creator_label}");
    if !license_name.is_empty() {
        let _ = write!(result, ", licensed under {LDQ}{license_name}{RDQ}");
        if !license_url.is_empty() {
            let _ = write!(result, " ({license_url})");
        }
    }
    result
}
