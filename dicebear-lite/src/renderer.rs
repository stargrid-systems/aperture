//! SVG serializer. Walks the canvas element tree and streams markup
//! byte-for-byte compatible with `DiceBear`'s `Renderer` for default options,
//! without allocating.
//!
//! Output order is `<defs>` (component variant bodies deduped, then the
//! clipPath) followed by the clipped body (background plus `<use>` references).
//! Because `<defs>` must precede the body but is discovered while walking it,
//! the renderer makes two deterministic passes: variant selection is fully
//! keyed by `(seed, key)`, so recomputing it is safe.

use core::fmt::{self, Write};

use crate::data::{self, AttrVal, CANVAS_H, CANVAS_W, ComponentDef, METADATA, Node, SOURCE_NAME};
use crate::number::{equals, write_num};
use crate::prng::hash_u32;
use crate::resolver::Resolver;
use crate::xml::escape_into;

/// Maximum distinct component defs produced by one avatar (star variants +
/// constellation + comet + animation). A small stack array dedupes them.
const MAX_DEFS: usize = 16;

pub fn render<W: Write>(seed: &str, out: &mut W) -> fmt::Result {
    let resolver = Resolver::new(seed);
    let hash = hash_u32(SOURCE_NAME, seed);

    out.write_str("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 ")?;
    write_num(out, CANVAS_W)?;
    out.write_str(" ")?;
    write_num(out, CANVAS_H)?;
    out.write_str("\" fill=\"none\" shape-rendering=\"auto\" aria-hidden=\"true\">")?;
    out.write_str("<!-- Generated by DiceBear (https://www.dicebear.com) -->")?;
    out.write_str(METADATA)?;
    out.write_str("<defs>")?;

    // Pass 1: each visible component's variant body, deduped by (source, variant).
    // Embedded <defs> (gradients) are diverted into the document <defs> first.
    let mut seen_g: [Option<(&'static str, &'static str)>; MAX_DEFS] = [None; MAX_DEFS];
    let mut seen_grad: [Option<&'static str>; MAX_DEFS] = [None; MAX_DEFS];
    for node in data::CANVAS {
        let &Node::Component { name, .. } = node else {
            continue;
        };
        let Some(variant) = resolver.variant(name) else {
            continue;
        };
        let component = data::component(name).expect("canvas references a known component");
        let source = component.extends.unwrap_or(name);
        if seen_g
            .iter()
            .flatten()
            .any(|(s, v)| *s == source && *v == variant)
        {
            continue;
        }
        for slot in &mut seen_g {
            if slot.is_none() {
                *slot = Some((source, variant));
                break;
            }
        }
        write_def(
            out,
            &resolver,
            component,
            source,
            variant,
            hash,
            &mut seen_grad,
        )?;
    }

    // The clipPath is always applied (border radius defaults to 0).
    out.write_str("<clipPath id=\"clip-")?;
    write!(out, "{hash:08x}")?;
    out.write_str("\"><rect width=\"")?;
    write_num(out, CANVAS_W)?;
    out.write_str("\" height=\"")?;
    write_num(out, CANVAS_H)?;
    out.write_str("\" rx=\"0\" ry=\"0\"/></clipPath></defs>")?;

    out.write_str("<g clip-path=\"url(#clip-")?;
    write!(out, "{hash:08x}")?;
    out.write_str(")\"><rect width=\"")?;
    write_num(out, CANVAS_W)?;
    out.write_str("\" height=\"")?;
    write_num(out, CANVAS_H)?;
    out.write_str("\" fill=\"")?;
    escape_into(out, resolver.color("background"))?;
    out.write_str("\"/>")?;

    // Pass 2: emit one <use> per visible component.
    for node in data::CANVAS {
        let &Node::Component { name, attrs } = node else {
            continue;
        };
        let Some(variant) = resolver.variant(name) else {
            continue;
        };
        let component = data::component(name).expect("canvas references a known component");
        write_use(out, &resolver, name, component, variant, attrs, hash)?;
    }

    out.write_str("</g></svg>")
}

/// Follows a component's `extends` alias to its source (one hop).
fn resolve(component: &ComponentDef) -> &ComponentDef {
    if let Some(source) = component.extends
        && let Some(resolved) = data::component(source)
    {
        return resolved;
    }
    component
}

/// Writes a component's def: embedded `<defs>` (gradients) are diverted into
/// the document `<defs>` (deduped by id), then the variant body is wrapped in
/// `<g id="...">`. Matches `DiceBear`, which renders the variant tree and
/// diverts `<defs>` children before registering the `<g>`.
fn write_def<W: Write>(
    out: &mut W,
    resolver: &Resolver<'_>,
    component: &ComponentDef,
    source: &'static str,
    variant: &'static str,
    hash: u32,
    seen_grad: &mut [Option<&'static str>; MAX_DEFS],
) -> fmt::Result {
    let base = resolve(component);
    let Some((_, def)) = base.variants.iter().find(|(n, _)| n == &variant) else {
        return Ok(());
    };

    // Recursively divert any `<defs>` (at any depth): their children (gradients)
    // go into the document <defs>, deduped by id. Children without an id are
    // never deduped.
    divert_defs(out, resolver, def.elements, seen_grad)?;

    out.write_str("<g id=\"")?;
    out.write_str(source)?;
    out.write_str("-")?;
    out.write_str(variant)?;
    out.write_str("-")?;
    write!(out, "{hash:08x}")?;
    out.write_str("\">")?;
    for el in def.elements {
        if !matches!(el, Node::El { name: "defs", .. }) {
            write_node(out, resolver, el)?;
        }
    }
    out.write_str("</g>")
}

/// Returns the `id` attribute of an element node, if it has a literal one.
fn node_id(node: &Node) -> Option<&'static str> {
    let Node::El { attrs, .. } = node else {
        return None;
    };
    for &(key, value) in *attrs {
        if key == "id"
            && let AttrVal::Lit(s) = value
        {
            return Some(s);
        }
    }
    None
}

/// Writes a `<use>` reference with the merged placement + component transform.
fn write_use<W: Write>(
    out: &mut W,
    resolver: &Resolver<'_>,
    name: &'static str,
    component: &ComponentDef,
    variant: &'static str,
    attrs: &'static [(&'static str, AttrVal)],
    hash: u32,
) -> fmt::Result {
    let source = component.extends.unwrap_or(name);
    let base = resolve(component);
    let transform = resolver.component_transform(name);
    let width = base.width.unwrap_or(0.0);
    let height = base.height.unwrap_or(0.0);
    let cx = width / 2.0;
    let cy = height / 2.0;

    let user_transform = attrs.iter().find_map(|(k, v)| {
        if *k == "transform"
            && let AttrVal::Lit(s) = v
        {
            return Some(*s);
        }
        None
    });
    let has_translate = !equals(transform.translate_x, 0.0) || !equals(transform.translate_y, 0.0);
    let has_rotate = !equals(transform.rotate, 0.0);
    let has_scale = !equals(transform.scale, 1.0);

    out.write_str("<use")?;
    if user_transform.is_some() || has_translate || has_rotate || has_scale {
        out.write_str(" transform=\"")?;
        let mut wrote = user_transform.is_some();
        if let Some(ut) = user_transform {
            out.write_str(ut)?;
        }
        if has_translate {
            if wrote {
                out.write_str(" ")?;
            }
            out.write_str("translate(")?;
            write_num(out, transform.translate_x / 100.0 * width)?;
            out.write_str(", ")?;
            write_num(out, transform.translate_y / 100.0 * height)?;
            out.write_str(")")?;
            wrote = true;
        }
        if has_rotate {
            if wrote {
                out.write_str(" ")?;
            }
            out.write_str("rotate(")?;
            write_num(out, transform.rotate)?;
            out.write_str(", ")?;
            write_num(out, cx)?;
            out.write_str(", ")?;
            write_num(out, cy)?;
            out.write_str(")")?;
            wrote = true;
        }
        if has_scale {
            if wrote {
                out.write_str(" ")?;
            }
            out.write_str("translate(")?;
            write_num(out, cx)?;
            out.write_str(", ")?;
            write_num(out, cy)?;
            out.write_str(") scale(")?;
            write_num(out, transform.scale)?;
            out.write_str(") translate(")?;
            write_num(out, -cx)?;
            out.write_str(", ")?;
            write_num(out, -cy)?;
            out.write_str(")")?;
        }
        out.write_str("\"")?;
    }
    out.write_str(" href=\"#")?;
    out.write_str(source)?;
    out.write_str("-")?;
    out.write_str(variant)?;
    out.write_str("-")?;
    write!(out, "{hash:08x}")?;
    out.write_str("\"/>")
}

fn write_nodes<W: Write>(out: &mut W, resolver: &Resolver<'_>, nodes: &[Node]) -> fmt::Result {
    for node in nodes {
        write_node(out, resolver, node)?;
    }
    Ok(())
}

fn write_node<W: Write>(out: &mut W, resolver: &Resolver<'_>, node: &Node) -> fmt::Result {
    // `<defs>` are diverted into the document `<defs>` by `divert_defs`, so they
    // never render inline anywhere in the tree.
    if let Node::El { name: "defs", .. } = node {
        return Ok(());
    }
    match node {
        Node::El {
            name,
            attrs,
            children,
        } => {
            out.write_str("<")?;
            out.write_str(name)?;
            write_attrs(out, resolver, attrs)?;
            if children.is_empty() {
                out.write_str("/>")
            } else {
                out.write_str(">")?;
                write_nodes(out, resolver, children)?;
                out.write_str("</")?;
                out.write_str(name)?;
                out.write_str(">")
            }
        }
        // Component references do not nest inside variant element trees.
        Node::Component { .. } => Ok(()),
    }
}

fn write_attrs<W: Write>(
    out: &mut W,
    resolver: &Resolver<'_>,
    attrs: &[(&'static str, AttrVal)],
) -> fmt::Result {
    for (key, value) in attrs {
        out.write_str(" ")?;
        out.write_str(key)?;
        out.write_str("=\"")?;
        match value {
            AttrVal::Lit(s) => escape_into(out, s)?,
            AttrVal::Color(name) => escape_into(out, resolver.color(name))?,
        }
        out.write_str("\"")?;
    }
    Ok(())
}

/// Depth-first walk that diverts every `<defs>` element's children into the
/// document `<defs>`, deduped by id (children without an id are never deduped).
fn divert_defs<W: Write>(
    out: &mut W,
    resolver: &Resolver<'_>,
    nodes: &[Node],
    seen_grad: &mut [Option<&'static str>; MAX_DEFS],
) -> fmt::Result {
    for node in nodes {
        if let Node::El {
            name: "defs",
            children,
            ..
        } = node
        {
            for child in *children {
                let id = node_id(child);
                let already = id.is_some_and(|i| seen_grad.iter().flatten().any(|s| *s == i));
                if !already {
                    if let Some(i) = id {
                        for slot in seen_grad.iter_mut() {
                            if slot.is_none() {
                                *slot = Some(i);
                                break;
                            }
                        }
                    }
                    write_node(out, resolver, child)?;
                }
            }
        } else if let Node::El { children, .. } = node {
            divert_defs(out, resolver, children, seen_grad)?;
        }
    }
    Ok(())
}
